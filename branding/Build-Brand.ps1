[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'cn-mark.svg')).Replace("`r`n", "`n").Trim()
[xml]$document = $source
$letters = $document.SelectSingleNode('//*[@id="cn-letters"]').OuterXml
$tile = $document.SelectSingleNode('//*[@id="cn-tile"]').OuterXml
$media = 'harmony\AppScope\resources\base\media'
$outputs = @{}
$outputs[(Join-Path $media 'cn_mark.svg')] = $source
$outputs['desktop-plugin\brand.svg'] = $source
$outputs['desktop-plugin\lib\brand.mjs'] = ('// Generated by branding/Build-Brand.ps1 from cn-mark.svg.' + "`n" + 'export const BRAND_SVG = ') + ($source | ConvertTo-Json -Compress) + ';'
$outputs[(Join-Path $media 'app_icon_foreground.svg')] = '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 32 32">' + $letters + '</svg>'
$outputs[(Join-Path $media 'app_icon_background.svg')] = '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 32 32"><rect width="32" height="32" fill="#171717"/></svg>'
foreach ($mode in @('base','dark')) {
    $device = if ($mode -eq 'dark') { '#BCC3CE' } else { '#343941' }
    $screen = if ($mode -eq 'dark') { '#303743' } else { '#E8ECF5' }
    $stand = if ($mode -eq 'dark') { '#606976' } else { '#BEC5D0' }
    $shadow = if ($mode -eq 'dark') { '#000000' } else { '#202329' }
    $cover = '<svg xmlns="http://www.w3.org/2000/svg" width="280" height="190" viewBox="0 0 280 190" fill="none">' +
        '<ellipse cx="140" cy="173" rx="92" ry="6" fill="' + $shadow + '" fill-opacity=".05"/>' +
        '<rect x="38" y="20" width="204" height="130" rx="12" fill="' + $device + '"/>' +
        '<rect x="45" y="27" width="190" height="110" rx="6" fill="' + $screen + '"/>' +
        '<path d="M126 151h28l4 19h-36l4-19Z" fill="' + $stand + '"/>' +
        '<path d="M111 172h58" stroke="' + $stand + '" stroke-width="5" stroke-linecap="round"/>' +
        '<g transform="translate(119 60) scale(1.34375)">' + $tile + $letters + '</g>' +
        '<circle cx="140" cy="144" r="2" fill="' + $stand + '"/></svg>'
    $outputs['harmony\entry\src\main\resources\' + $mode + '\media\computer_cover.svg'] = $cover
}
foreach ($relative in $outputs.Keys) {
    $destination = Join-Path $projectRoot $relative
    $expected = $outputs[$relative] + "`n"
    if ($Check) {
        if (!(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination) -cne $expected) { throw ('Brand asset is out of date: ' + $relative) }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path -Parent $destination)) | Out-Null
        [IO.File]::WriteAllText($destination, $expected, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('Cn brand assets ' + $(if ($Check) { 'verified' } else { 'generated' }) + ': ' + $outputs.Count)
