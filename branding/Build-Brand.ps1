[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$lf = [string][char]10
$source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'cn-mark.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
[xml]$darkDocument = $source
[xml]$lightDocument = $source
$lightTile = $lightDocument.SelectSingleNode('//*[@id="cn-tile"]')
$lightTile.SetAttribute('fill', '#ffffff')
$lightTile.SetAttribute('stroke', '#d7d7d7')
$lightTile.SetAttribute('stroke-width', '0.75')
$lightDocument.SelectSingleNode('//*[@id="cn-letters"]').SetAttribute('stroke', '#171717')
$light = $lightDocument.OuterXml
$adaptiveStyle = '<style>#cn-tile{fill:#fff;stroke:#d7d7d7;stroke-width:.75}#cn-letters{stroke:#171717}@media(prefers-color-scheme:dark){#cn-tile{fill:#171717;stroke:none}#cn-letters{stroke:#fff}}</style>'
$adaptive = $source.Replace('</svg>', $adaptiveStyle + '</svg>')
$outputs = @{}
$outputs['branding\cn-mark-dark.svg'] = $source
$outputs['branding\cn-mark-light.svg'] = $light
$outputs['desktop-plugin\brand.svg'] = $adaptive
$outputs['desktop-plugin\lib\brand.mjs'] = '// Generated by branding/Build-Brand.ps1 from cn-mark.svg.' + $lf + 'export const BRAND_SVG = ' + ($adaptive | ConvertTo-Json -Compress) + ';'
foreach ($mode in @('base','dark')) {
    $document = if ($mode -eq 'dark') { $darkDocument } else { $lightDocument }
    $mark = if ($mode -eq 'dark') { $source } else { $light }
    $letters = $document.SelectSingleNode('//*[@id="cn-letters"]').OuterXml
    $tile = $document.SelectSingleNode('//*[@id="cn-tile"]').OuterXml
    $background = if ($mode -eq 'dark') { '#171717' } else { '#ffffff' }
    $appMedia = 'harmony\AppScope\resources\' + $mode + '\media\'
    $outputs[$appMedia + 'cn_mark.svg'] = $mark
    $outputs[$appMedia + 'app_icon_foreground.svg'] = '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 32 32">' + $letters + '</svg>'
    $outputs[$appMedia + 'app_icon_background.svg'] = '<svg xmlns="http://www.w3.org/2000/svg" width="360" height="360" viewBox="0 0 32 32"><rect width="32" height="32" fill="' + $background + '"/></svg>'
    $device = if ($mode -eq 'dark') { '#BCC3CE' } else { '#343941' }
    $screen = if ($mode -eq 'dark') { '#303743' } else { '#E8ECF5' }
    $stand = if ($mode -eq 'dark') { '#606976' } else { '#BEC5D0' }
    $shadow = if ($mode -eq 'dark') { '#000000' } else { '#202329' }
    $cover = '<svg xmlns="http://www.w3.org/2000/svg" width="280" height="190" viewBox="0 0 280 190" fill="none">' +
        '<ellipse cx="140" cy="173" rx="92" ry="6" fill="' + $shadow + '" fill-opacity=".05"/>' +
        '<rect x="38" y="20" width="204" height="130" rx="12" fill="' + $device + '"/>' +
        '<rect x="45" y="27" width="190" height="110" rx="6" fill="' + $screen + '"/>' +
        '<path d="M126 151h28l4 19h-36l4-19Z" fill="' + $stand + '"/>' +
        '<path d="M111 172h58" stroke="' + $stand + '" stroke-width="5" stroke-linecap="round"/>' +
        '<g transform="translate(119 60) scale(1.34375)">' + $tile + $letters + '</g>' +
        '<circle cx="140" cy="144" r="2" fill="' + $stand + '"/></svg>'
    $outputs['harmony\entry\src\main\resources\' + $mode + '\media\computer_cover.svg'] = $cover
}
foreach ($relative in $outputs.Keys) {
    $destination = Join-Path $projectRoot $relative
    $expected = $outputs[$relative] + $lf
    if ($Check) {
        if (!(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination) -cne $expected) { throw ('Brand asset is out of date: ' + $relative) }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path -Parent $destination)) | Out-Null
        [IO.File]::WriteAllText($destination, $expected, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('Cn theme assets ' + $(if ($Check) { 'verified' } else { 'generated' }) + ': ' + $outputs.Count)
