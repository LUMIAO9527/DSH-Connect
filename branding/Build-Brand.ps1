[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$lf = [string][char]10
$source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'r1c-mark.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
$glyph = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'r1c-glyph.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
# Official DeepSeek Harness welcome lockup, extracted from the installed DSH app.
$lockup = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'dsh-lockup.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
# The splash page stacks the whale above the wordmark, so both are split out.
$whaleMark = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'dsh-whale-mark.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
$wordmark = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'dsh-wordmark.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
$escape = { param($value) ($value | ConvertTo-Json -Compress).Replace('<', '\u003c').Replace('>', '\u003e').Replace('&', '\u0026').Replace("'", '\u0027') }
# The app icon is a full-bleed square so every launcher can apply its own corner
# mask. Inside DSH settings the sidebar icon is the monochrome mark.
# The HarmonyOS app was retired on 2026-11-07; its resources now live in
# _wip/AUTO_20261107ArchiveApp and are no longer generated.
$outputs = @{}
$outputs['branding\r1c-mark-dark.svg'] = $source
$outputs['branding\r1c-mark-light.svg'] = $source
$outputs['desktop-plugin\brand.svg'] = $glyph
$outputs['desktop-plugin\icon.svg'] = $source
$outputs['desktop-plugin\lib\brand.mjs'] = @(
    '// Generated by branding/Build-Brand.ps1 from the DSH Connect mark and the official DSH lockup assets.'
    'export const BRAND_SVG = ' + (& $escape $glyph) + ';'
    'export const BRAND_LOCKUP_SVG = ' + (& $escape $lockup) + ';'
    'export const BRAND_WHALE_SVG = ' + (& $escape $whaleMark) + ';'
    'export const BRAND_WORDMARK_SVG = ' + (& $escape $wordmark) + ';'
) -join $lf
# Home-screen icons rendered from the DSH Connect mark. The browser entry serves
# them from public gateway routes so a saved shortcut never falls back to a
# generic system icon while the page itself still requires device authorization.
$iconFiles = @{
    'apple-touch-icon.png' = 'dsh-apple-touch-icon.png'
    'icon-192.png' = 'dsh-icon-192.png'
    'icon-512.png' = 'dsh-icon-512.png'
    'icon-maskable-512.png' = 'dsh-icon-maskable-512.png'
}
$iconLines = foreach ($name in @('apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png')) {
    $bytes = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $PSScriptRoot $iconFiles[$name])))
    '    ' + ($name | ConvertTo-Json -Compress) + ': ' + ("'data:image/png;base64,$bytes'" | ConvertTo-Json -Compress)
}
$outputs['desktop-plugin\lib\icons.mjs'] = @(
    '// Generated by branding/Build-Brand.ps1 from the DSH Connect app icons.'
    'export const APP_ICONS = Object.freeze({'
    ($iconLines -join (',' + $lf))
    '});'
) -join $lf
foreach ($relative in $outputs.Keys) {
    $destination = Join-Path $projectRoot $relative
    $expected = $outputs[$relative] + $lf
    if ($Check) {
        if (!(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination) -cne $expected) { throw ('Brand asset is out of date: ' + $relative) }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path -Parent $destination)) | Out-Null
        [IO.File]::WriteAllText($destination, $expected, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('Brand assets ' + $(if ($Check) { 'verified' } else { 'generated' }) + ': ' + $outputs.Count)