[CmdletBinding()]
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$lf = [string][char]10
$source = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'cn-mark.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
$pluginSource = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'cn-mark-white.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
# Official DeepSeek Harness welcome lockup, extracted from the installed DSH app.
$lockup = [IO.File]::ReadAllText((Join-Path $PSScriptRoot 'dsh-lockup.svg')).Replace(([string][char]13 + [char]10), $lf).Trim()
# The desktop plugin keeps the white Cn tile so the mark stays legible in light
# and dark settings pages. The HarmonyOS app was retired on 2026-11-07; its
# resources now live in _wip/AUTO_20261107ArchiveApp and are no longer generated.
$webMark = $pluginSource
$outputs = @{}
$outputs['branding\cn-mark-dark.svg'] = $source
$outputs['branding\cn-mark-light.svg'] = $source
$outputs['desktop-plugin\brand.svg'] = $webMark
$outputs['desktop-plugin\icon.svg'] = $webMark
$webJson = ($webMark | ConvertTo-Json -Compress).Replace('<', '\u003c').Replace('>', '\u003e').Replace('&', '\u0026').Replace("'", '\u0027')
$lockupJson = ($lockup | ConvertTo-Json -Compress).Replace('<', '\u003c').Replace('>', '\u003e').Replace('&', '\u0026').Replace("'", '\u0027')
$outputs['desktop-plugin\lib\brand.mjs'] = @(
    '// Generated by branding/Build-Brand.ps1 from cn-mark-white.svg and dsh-lockup.svg.'
    'export const BRAND_SVG = ' + $webJson + ';'
    'export const BRAND_LOCKUP_SVG = ' + $lockupJson + ';'
) -join $lf
# Home-screen icons shipped by the DSH web frontend. The browser entry serves
# them from public gateway routes so a saved shortcut never falls back to a
# generic system icon while the page itself still requires device authorization.
$iconFiles = @{
    'apple-touch-icon.png' = 'dsh-apple-touch-icon.png'
    'icon-192.png' = 'dsh-icon-192.png'
    'icon-512.png' = 'dsh-icon-512.png'
    'icon-maskable-512.png' = 'dsh-icon-maskable-512.png'
}
$iconLines = foreach ($name in @('apple-touch-icon.png', 'icon-192.png', 'icon-512.png', 'icon-maskable-512.png')) {
    $bytes = [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $PSScriptRoot $iconFiles[$name])))
    '    ' + ($name | ConvertTo-Json -Compress) + ': ' + ("'data:image/png;base64,$bytes'" | ConvertTo-Json -Compress)
}
$outputs['desktop-plugin\lib\icons.mjs'] = @(
    '// Generated by branding/Build-Brand.ps1 from the official DeepSeek Harness app icons.'
    'export const APP_ICONS = Object.freeze({'
    ($iconLines -join (',' + $lf))
    '});'
) -join $lf
foreach ($relative in $outputs.Keys) {
    $destination = Join-Path $projectRoot $relative
    $expected = $outputs[$relative] + $lf
    if ($Check) {
        if (!(Test-Path -LiteralPath $destination) -or [IO.File]::ReadAllText($destination) -cne $expected) { throw ('Brand asset is out of date: ' + $relative) }
    } else {
        [IO.Directory]::CreateDirectory((Split-Path -Parent $destination)) | Out-Null
        [IO.File]::WriteAllText($destination, $expected, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('Brand assets ' + $(if ($Check) { 'verified' } else { 'generated' }) + ': ' + $outputs.Count)